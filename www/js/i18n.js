export class PortugueseMessageProvider extends MapBasedMessageProvider { constructor() { super(PT); } }
export class EnglishMessageProvider extends MapBasedMessageProvider { constructor() { super(EN); } }

// Serviço de idioma ativo (composition root do i18n).
export const I18n = {
  providers: { pt: new PortugueseMessageProvider(), en: new EnglishMessageProvider() },
  lang: 'pt',
  set(lang) { if (this.providers[lang]) this.lang = lang; },
  t(key, ...args) { return this.providers[this.lang].getMessage(key, ...args); },
  // Resolve argumentos "@chave" (nomes traduzíveis) em texto do idioma atual.
  resolve(arg) {
    if (typeof arg === 'string' && arg.startsWith('@')) {
      const [k, ...rest] = arg.slice(1).split('|');
      return this.t(k, ...rest.map((r) => this.resolve(r)));
    }
    return arg;
  },
};
export const t = (key, ...args) => I18n.t(key, ...args);
