// Camada de internacionalização (i18n) — mesma ideia do PDF: MessageProvider (interface),
// MapBasedMessageProvider (base abstrata) e um provedor por idioma. Novos idiomas = nova classe.

export class MessageProvider {
  getMessage(/* key, ...args */) { throw new Error('MessageProvider.getMessage não implementado'); }
}

export class MapBasedMessageProvider extends MessageProvider {
  constructor(messages) { super(); this.messages = messages; }
  getMessage(key, ...args) {
    const tpl = this.messages[key] ?? key;
    return tpl.replace(/\{(\d+)\}/g, (_, i) => (args[i] ?? ''));
  }
}

